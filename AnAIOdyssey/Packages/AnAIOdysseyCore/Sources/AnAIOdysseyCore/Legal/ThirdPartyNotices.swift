import Foundation

/// One entry in Settings > About > Acknowledgements: a bundled package (or
/// the app itself) and the license files that ship with it.
public struct ThirdPartyNotice: Decodable, Identifiable, Hashable, Sendable {
    public let id: String
    public let name: String
    /// SPDX identifier, e.g. `MIT`, `Apache-2.0`, `AGPL-3.0-or-later`.
    public let license: String
    public let version: String?
    public let url: String?
    public let note: String?
    /// Whether the package's code is part of the app binary.
    public let linked: Bool?
    /// License and NOTICE files in the notices folder, in display order.
    public let files: [String]
}

/// `ThirdPartyNotices/manifest.json`, generated by
/// `Scripts/generate_third_party_notices.py` from Package.resolved.
public struct ThirdPartyNoticesManifest: Decodable, Sendable {
    public let packages: [ThirdPartyNotice]
    public let app: ThirdPartyNotice
}

public enum ThirdPartyNotices {
    /// Folder copied into the app bundle (and kept in the repo next to
    /// THIRD_PARTY_NOTICES.md, which is generated from the same files).
    public static let folderName = "ThirdPartyNotices"

    public static func bundledDirectory(in bundle: Bundle = .main) -> URL? {
        guard let url = bundle.resourceURL?.appendingPathComponent(folderName, isDirectory: true),
              FileManager.default.fileExists(atPath: url.appendingPathComponent("manifest.json").path)
        else { return nil }
        return url
    }

    public static func load(directory: URL) throws -> ThirdPartyNoticesManifest {
        let data = try Data(contentsOf: directory.appendingPathComponent("manifest.json"))
        return try JSONDecoder().decode(ThirdPartyNoticesManifest.self, from: data)
    }

    public static func text(of file: String, in directory: URL) throws -> String {
        try String(contentsOf: directory.appendingPathComponent(file), encoding: .utf8)
    }
}
